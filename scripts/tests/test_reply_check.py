def _mix_metadata(text, other):
    meta = [l for l in other.split('\n') if l.startswith(('S1_EVIDENCE_FILE=', 'S1_SHA256SUMS_FILE=', 'S1_EVIDENCE_JSON='))]
    lines = [l for l in text.split('\n') if not l.startswith(('S1_EVIDENCE_FILE=', 'S1_SHA256SUMS_FILE=', 'S1_EVIDENCE_JSON='))]
    return '\n'.join(lines + meta) + '\n'


