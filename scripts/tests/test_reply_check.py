def _files(task, step, code, bounded, listed, prompt=PROMPT_BYTES):
    control = json.dumps({'task_id': task, 'prompt_sha256': hashlib.sha256(prompt).hexdigest(), 'runner_sha256': 'c' * 64,
                          'done': STEPS[:STEPS.index(step)], 'halted': step + ':' + code}, indent=2) + '\n'
    files = {task + '-prompt.txt': prompt, task + '-control.json': control.encode()}
    if listed and step in rc.STAGES:
        files[task + '-bounded-' + rc.STAGES[step][0].lower() + '.txt'] = bounded
    return files


def _meta(task, step, code, files):
    records = [{'file': n, 'bytes': len(b), 'sha256': hashlib.sha256(b).hexdigest()} for n, b in files.items()]
    payload = {'schema_version': 1, 'kind': 'S1_METADATA_ONLY', 'task_id': task, 'step': step, 's1_code': code,
               'complete_capture': False, 'unpublished_commit_bundle': 'NOT_COLLECTED', 'git_snapshot': 'NOT_COLLECTED',
               'gate_records': 'NOT_COLLECTED', 'files': records,
               'next_step': 'USER_FORWARD_METADATA_TO_ACTIVE_AUDITOR_KEEP_ORIGINAL_S1_EVIDENCE'}
    raw = json.dumps(payload, sort_keys=True, ensure_ascii=True, separators=(',', ':'))
    sums = ''.join(r['sha256'] + '  ' + r['file'] + '\n' for r in records).encode('ascii')
    lines = ['S1_EVIDENCE_FILE=.git/' + task + '-s1-evidence.json sha256=' + hashlib.sha256((raw + '\n').encode()).hexdigest(),
             'S1_SHA256SUMS_FILE=.git/' + task + '-s1-SHA256SUMS.txt sha256=' + hashlib.sha256(sums).hexdigest(),
             'S1_EVIDENCE_JSON=' + raw]
    return raw, sums, lines


def _zip(members, omit_from_manifest=None):
    manifest = ''.join(hashlib.sha256(members[n]).hexdigest() + '  ' + n + '\n' for n in sorted(members)
                       if n != omit_from_manifest).encode('ascii')
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, 'w') as z:
        for n in sorted(list(members) + ['SHA256SUMS.txt']):
            z.writestr(n, manifest if n == 'SHA256SUMS.txt' else members[n])
    return buf.getvalue(), manifest


def _capture(task, step, code, members, base=BASE, archive=None, omit=None):
    data, manifest = _zip(members, omit)
    card = {'schema_version': 1, 'kind': 'S1_FULL_CAPTURE', 'complete_capture': True, 'task_id': task, 'step': step,
            's1_code': code, 'base_oid': base, 'head_oid': base, 'archive_file': archive or task + '-s1-full-capture.zip',
            'archive_sha256': hashlib.sha256(data).hexdigest(), 'bundle_file': task + '-s1.bundle',
            'manifest_sha256': hashlib.sha256(manifest).hexdigest(), 'archive_member_count': len(members) + 1}
    raw = json.dumps(card, sort_keys=True, separators=(',', ':'))
    lines = ['S1_FULL_CAPTURE_FILE=.git/' + task + '-s1-full-capture.zip sha256=' + hashlib.sha256(data).hexdigest(),
             'S1_FULL_CAPTURE_CARD=.git/' + task + '-s1-full-capture.json sha256=' + hashlib.sha256((raw + '\n').encode()).hexdigest(),
             'S1_FULL_CAPTURE_JSON=' + raw]
    return data, lines


def s1_reply(step, code, bounded=b'1 failed, 266 passed\n', listed=True, bounded_line=None, metadata=True,
             capture=False, already_halted=False, members_edit=None, card_base=BASE, zip_prompt=PROMPT_BYTES,
             omit=None):
    task = PROD_TASK
    files = _files(task, step, code, bounded, listed)
    lines = ['Ran command: `python scripts/batch_runner.py --task-id ' + task + ' ' + step + '`']
    lines.append('S1 TASK_ALREADY_HALTED ' + step + ':' + code if already_halted else 'S1 ' + code + ' | step ' + step)
    data = None
    if not already_halted:
        if bounded_line:
            lines.append(bounded_line)
        if metadata:
            raw, sums, meta_lines = _meta(task, step, code, files)
            lines += meta_lines
        else:
            lines.append('S1_EVIDENCE_STATUS=UNAVAILABLE')
        if capture:
            members = dict(files)
            members[task + '-prompt.txt'] = zip_prompt
            members[task + '-s1-evidence.json'] = (raw + '\n').encode()
            members[task + '-s1-SHA256SUMS.txt'] = sums
            members[task + '-s1.bundle'] = b'bundle bytes'
            if members_edit:
                members_edit(members)
            data, cap = _capture(task, step, code, members, base=card_base, omit=omit)
            lines += cap
        else:
            lines.append('S1_FULL_CAPTURE_STATUS=INCOMPLETE_UNTRACKED_FILES')
